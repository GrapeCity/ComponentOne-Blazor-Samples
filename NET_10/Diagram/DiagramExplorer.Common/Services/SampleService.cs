using System.Collections.Generic;
using DiagramExplorer.Models;

namespace DiagramExplorer.Services;

public class SampleService
{
    private readonly List<SampleNode> _tree;

    public SampleService()
    {
        _tree = BuildTree();
    }

    public List<SampleNode> GetSamples() => _tree;

    public SampleNode? FindFirstSample() => FindFirst(_tree);

    private static SampleNode? FindFirst(IEnumerable<SampleNode> nodes)
    {
        foreach (var n in nodes)
        {
            if (n is not null) return n;
            var found = FindFirst(n.Children);
            if (found is not null) return found;
        }
        return null;
    }

